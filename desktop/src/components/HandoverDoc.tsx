import * as React from "react";
import { Copy, Check, FileText } from "lucide-react";

import { pipeline, answers, staleness } from "@/lib/data";

/** Compose a handover / onboarding document from the indexed corpus (FR-12). */
function buildMarkdown(): string {
  const lines: string[] = [];
  lines.push(`# Handover: ${pipeline.name}`);
  lines.push("");
  lines.push(`> ${pipeline.family}`);
  lines.push("");
  lines.push(`**Repository:** \`${pipeline.repo}\``);
  lines.push(
    `**Original author:** ${pipeline.author.name} (${pipeline.author.role}), departed ${pipeline.author.departed}`,
  );
  lines.push(
    `**Corpus:** ${pipeline.stats.files} files · ${pipeline.stats.conversations} conversations · ${pipeline.stats.commits} commits`,
  );
  lines.push("");
  lines.push(`## Purpose`);
  lines.push(pipeline.description);
  lines.push("");

  lines.push(`## Key decisions (reconstructed, with citations)`);
  for (const a of answers) {
    lines.push("");
    lines.push(`### ${a.question}`);
    lines.push(a.technical.summary);
    const codeCites = a.codeCitations
      .map((c) => `\`${c.path}:${c.lineStart}\` (${c.symbol})`)
      .join(", ");
    if (codeCites) lines.push(`- **Code:** ${codeCites}`);
    if (a.conversationCitations.length)
      lines.push(`- **Conversation:** ${a.conversationCitations.join(", ")}`);
  }

  lines.push("");
  lines.push(`## Versions & reference builds`);
  lines.push("");
  lines.push(`| Item | Pinned | Current | Status |`);
  lines.push(`| --- | --- | --- | --- |`);
  for (const s of staleness) {
    lines.push(`| ${s.name} | ${s.pinned} | ${s.current} | ${s.status} |`);
  }
  lines.push("");
  lines.push(`---`);
  lines.push(`_Generated by Libbie from sample data. Every claim above is dual-cited to code and conversation._`);
  return lines.join("\n");
}

export function HandoverDoc() {
  const md = React.useMemo(buildMarkdown, []);
  const [copied, setCopied] = React.useState(false);

  const copy = async () => {
    try {
      await navigator.clipboard.writeText(md);
      setCopied(true);
      setTimeout(() => setCopied(false), 1800);
    } catch {
      /* clipboard may be unavailable */
    }
  };

  return (
    <div>
      <div className="mb-4 flex items-center justify-between">
        <p className="flex items-center gap-2 text-[13px] text-muted-foreground">
          <FileText className="size-4 text-primary" aria-hidden />
          A structured handover, assembled from the indexed corpus.
        </p>
        <button
          type="button"
          onClick={copy}
          className="inline-flex items-center gap-1.5 rounded-full bg-primary px-3 py-1.5 text-[12px] font-medium text-primary-foreground"
        >
          {copied ? <Check className="size-3.5" aria-hidden /> : <Copy className="size-3.5" aria-hidden />}
          {copied ? "Copied" : "Copy Markdown"}
        </button>
      </div>
      <pre className="scroll-soft selectable overflow-x-auto whitespace-pre-wrap rounded-xl border border-border bg-muted/40 p-4 font-mono text-[11.5px] leading-relaxed text-foreground">
        {md}
      </pre>
    </div>
  );
}
